-- Sổ Tự Học — schema snapshot generator (read-only).
--
-- Produces the DDL of the application schemas as ordered rows (ord, name, ddl). It reads only the
-- system catalogs: no table rows, no secrets. installer/snapshot/assemble.mjs turns the rows into
-- installer/sql/10-baseline.sql. Run it again whenever the production schema changes.
--
-- search_path is emptied so every name in the output is schema-qualified.
set search_path to '';

with app_ns as (
  select oid, nspname, nspacl, nspowner from pg_catalog.pg_namespace
  where nspname in ('auth_bag', 'bag_game', 'homework_private', 'public', 'storage_live_private')
),
ext_objs as (
  select objid from pg_catalog.pg_depend where deptype = 'e'
),
rels as (
  select c.* from pg_catalog.pg_class c
  where c.relnamespace in (select oid from app_ns) and c.oid not in (select objid from ext_objs)
),
tabs as (select * from rels where relkind in ('r', 'p')),
procs as (
  select p.* from pg_catalog.pg_proc p
  where p.pronamespace in (select oid from app_ns) and p.prokind in ('f', 'p')
    and p.oid not in (select objid from ext_objs)
),
std_roles(r) as (values ('public'), ('anon'), ('authenticated'), ('service_role')),
out(ord, name, ddl) as (
  -- 20 schemas (public already exists)
  select 20, n.nspname::text, format('create schema if not exists %I;', n.nspname)
  from app_ns n where n.nspname <> 'public'

  -- 30 enum types
  union all
  select 30, t.oid::pg_catalog.regtype::text,
    format('create type %s as enum (%s);', t.oid::pg_catalog.regtype,
      (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder)
       from pg_catalog.pg_enum e where e.enumtypid = t.oid))
  from pg_catalog.pg_type t
  where t.typnamespace in (select oid from app_ns) and t.typtype = 'e'
    and t.oid not in (select objid from ext_objs)

  -- 40 standalone / serial sequences (identity sequences come with their column)
  union all
  select 40, c.oid::pg_catalog.regclass::text,
    format('create sequence %s as %s increment by %s minvalue %s maxvalue %s start with %s cache %s%s;',
      c.oid::pg_catalog.regclass, s.seqtypid::pg_catalog.regtype, s.seqincrement, s.seqmin, s.seqmax,
      s.seqstart, s.seqcache, case when s.seqcycle then ' cycle' else '' end)
  from rels c join pg_catalog.pg_sequence s on s.seqrelid = c.oid
  where c.relkind = 'S'
    and not exists (select 1 from pg_catalog.pg_depend d where d.objid = c.oid and d.deptype = 'i')

  -- 50 tables (columns, types, identity, not null; defaults and constraints come later)
  union all
  select 50, t.oid::pg_catalog.regclass::text,
    format(E'create %stable %s (\n%s\n)%s;',
      case when t.relpersistence = 'u' then 'unlogged ' else '' end,
      t.oid::pg_catalog.regclass,
      coalesce((select string_agg(
          format('  %I %s%s%s%s', a.attname, pg_catalog.format_type(a.atttypid, a.atttypmod),
            case when a.attcollation <> 0 and a.attcollation <> ty.typcollation
              then ' collate ' || (select format('%I.%I', cn.nspname, co.collname)
                                   from pg_catalog.pg_collation co
                                   join pg_catalog.pg_namespace cn on cn.oid = co.collnamespace
                                   where co.oid = a.attcollation)
              else '' end,
            case a.attidentity when 'a' then ' generated always as identity'
                               when 'd' then ' generated by default as identity' else '' end,
            case when a.attgenerated = 's'
              then format(' generated always as (%s) stored',
                     pg_catalog.pg_get_expr(ad.adbin, ad.adrelid)) else '' end
            || case when a.attnotnull then ' not null' else '' end),
          E',\n' order by a.attnum)
        from pg_catalog.pg_attribute a
        join pg_catalog.pg_type ty on ty.oid = a.atttypid
        left join pg_catalog.pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
        where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped), ''),
      case when t.reloptions is not null
        then format(' with (%s)', array_to_string(t.reloptions, ', ')) else '' end)
  from tabs t

  -- 60 functions and procedures (bodies are not checked at creation)
  union all
  select 60, p.oid::pg_catalog.regprocedure::text,
    rtrim(pg_catalog.pg_get_functiondef(p.oid), E'\n') || ';'
  from procs p

  -- 70 column defaults
  union all
  select 70, format('%s.%s', a.attrelid::pg_catalog.regclass, a.attname),
    format('alter table %s alter column %I set default %s;', a.attrelid::pg_catalog.regclass,
      a.attname, pg_catalog.pg_get_expr(ad.adbin, ad.adrelid))
  from pg_catalog.pg_attrdef ad
  join pg_catalog.pg_attribute a on a.attrelid = ad.adrelid and a.attnum = ad.adnum
  where ad.adrelid in (select oid from tabs) and a.attgenerated = '' and a.attidentity = ''

  -- 80 primary key / unique / check / exclusion constraints; 85 foreign keys
  union all
  select case when co.contype = 'f' then 85 else 80 end,
    format('%s.%s', co.conrelid::pg_catalog.regclass, co.conname),
    format('alter table %s add constraint %I %s;', co.conrelid::pg_catalog.regclass, co.conname,
      pg_catalog.pg_get_constraintdef(co.oid))
  from pg_catalog.pg_constraint co
  where co.conrelid in (select oid from tabs) and co.contype in ('p', 'u', 'c', 'x', 'f')
    and co.conislocal

  -- 90 indexes not backing a constraint
  union all
  select 90, i.indexrelid::pg_catalog.regclass::text,
    pg_catalog.pg_get_indexdef(i.indexrelid) || ';'
  from pg_catalog.pg_index i
  where i.indrelid in (select oid from tabs)
    and not exists (select 1 from pg_catalog.pg_constraint co where co.conindid = i.indexrelid
                    and co.contype in ('p', 'u', 'x'))

  -- 100 views
  union all
  select 100, v.oid::pg_catalog.regclass::text,
    format(E'create view %s%s as\n%s;', v.oid::pg_catalog.regclass,
      case when v.reloptions is not null
        then format(' with (%s)', array_to_string(v.reloptions, ', ')) else '' end,
      regexp_replace(pg_catalog.pg_get_viewdef(v.oid, true), ';\s*$', ''))
  from rels v where v.relkind = 'v'

  -- 110 triggers on app tables, plus app triggers on other tables (auth.users)
  union all
  select 110, format('%s.%s', tg.tgrelid::pg_catalog.regclass, tg.tgname),
    pg_catalog.pg_get_triggerdef(tg.oid) || ';'
    || case when tg.tgenabled = 'D'
         then format(E'\nalter table %s disable trigger %I;', tg.tgrelid::pg_catalog.regclass, tg.tgname)
         else '' end
  from pg_catalog.pg_trigger tg
  where not tg.tgisinternal
    and (tg.tgrelid in (select oid from tabs) or tg.tgfoid in (select oid from procs))

  -- 120 row level security switches
  union all
  select 120, t.oid::pg_catalog.regclass::text,
    format('alter table %s enable row level security;', t.oid::pg_catalog.regclass)
    || case when t.relforcerowsecurity
         then format(E'\nalter table %s force row level security;', t.oid::pg_catalog.regclass)
         else '' end
  from tabs t where t.relrowsecurity

  -- 125 policies on app tables and on storage.objects
  union all
  select 125, format('%s.%s', pol.polrelid::pg_catalog.regclass, pol.polname),
    format('create policy %I on %s as %s for %s to %s%s%s;', pol.polname,
      pol.polrelid::pg_catalog.regclass,
      case when pol.polpermissive then 'permissive' else 'restrictive' end,
      case pol.polcmd when 'r' then 'select' when 'a' then 'insert' when 'w' then 'update'
                      when 'd' then 'delete' else 'all' end,
      case when pol.polroles = '{0}' then 'public'
        else (select string_agg(quote_ident(r.rolname), ', ' order by r.rolname)
              from pg_catalog.pg_roles r where r.oid = any (pol.polroles)) end,
      coalesce(' using (' || pg_catalog.pg_get_expr(pol.polqual, pol.polrelid) || ')', ''),
      coalesce(' with check (' || pg_catalog.pg_get_expr(pol.polwithcheck, pol.polrelid) || ')', ''))
  from pg_catalog.pg_policy pol
  where pol.polrelid in (select oid from tabs) or pol.polrelid = 'storage.objects'::pg_catalog.regclass

  -- 130 privileges: reset the standard roles, then grant exactly what production has
  union all
  select 130, format('schema %s', n.nspname),
    format('revoke all on schema %I from public, anon, authenticated, service_role;', n.nspname)
    || coalesce((select string_agg(format(E'\ngrant %s on schema %I to %s%s;', g.privs, n.nspname,
                   g.grantee, case when g.grantable then ' with grant option' else '' end), '')
                 from (select case when x.grantee = 0 then 'public' else quote_ident(pg_catalog.pg_get_userbyid(x.grantee)) end grantee,
                              x.is_grantable grantable, string_agg(x.privilege_type, ', ' order by x.privilege_type) privs
                       from aclexplode(coalesce(n.nspacl, acldefault('n'::"char", n.nspowner))) x
                       where x.grantee <> n.nspowner
                       group by 1, 2) g), '')
  from app_ns n where n.nspname <> 'public'

  union all
  select 131, c.oid::pg_catalog.regclass::text,
    format('revoke all on %s %s from public, anon, authenticated, service_role;',
      case when c.relkind = 'S' then 'sequence' else 'table' end, c.oid::pg_catalog.regclass)
    || coalesce((select string_agg(format(E'\ngrant %s on %s %s to %s%s;', g.privs,
                   case when c.relkind = 'S' then 'sequence' else 'table' end, c.oid::pg_catalog.regclass,
                   g.grantee, case when g.grantable then ' with grant option' else '' end), '')
                 from (select case when x.grantee = 0 then 'public' else quote_ident(pg_catalog.pg_get_userbyid(x.grantee)) end grantee,
                              x.is_grantable grantable, string_agg(x.privilege_type, ', ' order by x.privilege_type) privs
                       from aclexplode(coalesce(c.relacl, acldefault((case when c.relkind = 'S' then 's' else 'r' end)::"char", c.relowner))) x
                       where x.grantee <> c.relowner
                       group by 1, 2) g), '')
    || coalesce((select string_agg(format(E'\ngrant %s (%I) on table %s to %s%s;', x.privilege_type,
                   a.attname, c.oid::pg_catalog.regclass,
                   case when x.grantee = 0 then 'public' else quote_ident(pg_catalog.pg_get_userbyid(x.grantee)) end,
                   case when x.is_grantable then ' with grant option' else '' end), '' order by a.attnum, x.privilege_type)
                 from pg_catalog.pg_attribute a, aclexplode(a.attacl) x
                 where a.attrelid = c.oid and a.attacl is not null and x.grantee <> c.relowner), '')
  from rels c where c.relkind in ('r', 'p', 'v', 'm', 'S')

  union all
  select 132, p.oid::pg_catalog.regprocedure::text,
    format('revoke all on %s %s from public, anon, authenticated, service_role;',
      case when p.prokind = 'p' then 'procedure' else 'function' end, p.oid::pg_catalog.regprocedure)
    || coalesce((select string_agg(format(E'\ngrant %s on %s %s to %s%s;', x.privilege_type,
                   case when p.prokind = 'p' then 'procedure' else 'function' end, p.oid::pg_catalog.regprocedure,
                   case when x.grantee = 0 then 'public' else quote_ident(pg_catalog.pg_get_userbyid(x.grantee)) end,
                   case when x.is_grantable then ' with grant option' else '' end), '' order by x.grantee)
               from aclexplode(coalesce(p.proacl, acldefault('f'::"char", p.proowner))) x where x.grantee <> p.proowner), '')
  from procs p

  -- 140 comments
  union all
  select 140, c.oid::pg_catalog.regclass::text,
    format('comment on %s %s is %L;', case when c.relkind = 'v' then 'view' else 'table' end,
      c.oid::pg_catalog.regclass, d.description)
  from rels c join pg_catalog.pg_description d
    on d.objoid = c.oid and d.classoid = 'pg_catalog.pg_class'::pg_catalog.regclass and d.objsubid = 0
  where c.relkind in ('r', 'p', 'v')
  union all
  select 141, format('%s.%s', c.oid::pg_catalog.regclass, a.attname),
    format('comment on column %s.%I is %L;', c.oid::pg_catalog.regclass, a.attname, d.description)
  from rels c
  join pg_catalog.pg_attribute a on a.attrelid = c.oid and a.attnum > 0
  join pg_catalog.pg_description d
    on d.objoid = c.oid and d.classoid = 'pg_catalog.pg_class'::pg_catalog.regclass and d.objsubid = a.attnum
  where c.relkind in ('r', 'p', 'v')
  union all
  select 142, p.oid::pg_catalog.regprocedure::text,
    format('comment on %s %s is %L;', case when p.prokind = 'p' then 'procedure' else 'function' end,
      p.oid::pg_catalog.regprocedure, d.description)
  from procs p join pg_catalog.pg_description d
    on d.objoid = p.oid and d.classoid = 'pg_catalog.pg_proc'::pg_catalog.regclass
  union all
  select 143, n.nspname::text, format('comment on schema %I is %L;', n.nspname, d.description)
  from app_ns n join pg_catalog.pg_description d
    on d.objoid = n.oid and d.classoid = 'pg_catalog.pg_namespace'::pg_catalog.regclass
  where n.nspname <> 'public'

  -- 150 realtime publication and replica identity
  union all
  select 150, pr.prrelid::pg_catalog.regclass::text,
    format('alter publication supabase_realtime add table %s%s%s;', pr.prrelid::pg_catalog.regclass,
      case when pr.prattrs is not null
        then ' (' || (select string_agg(quote_ident(a.attname), ', ' order by a.attnum)
                      from pg_catalog.pg_attribute a
                      where a.attrelid = pr.prrelid and a.attnum = any (pr.prattrs)) || ')' else '' end,
      coalesce(' where (' || pg_catalog.pg_get_expr(pr.prqual, pr.prrelid) || ')', ''))
  from pg_catalog.pg_publication_rel pr
  join pg_catalog.pg_publication pb on pb.oid = pr.prpubid and pb.pubname = 'supabase_realtime'
  where pr.prrelid in (select oid from tabs)
  union all
  select 151, t.oid::pg_catalog.regclass::text,
    format('alter table %s replica identity %s;', t.oid::pg_catalog.regclass,
      case t.relreplident when 'f' then 'full' when 'n' then 'nothing'
        else 'using index ' || (select quote_ident(ic.relname) from pg_catalog.pg_index i
                                join pg_catalog.pg_class ic on ic.oid = i.indexrelid
                                where i.indrelid = t.oid and i.indisreplident) end)
  from tabs t where t.relreplident <> 'd'

  -- 160 storage buckets
  union all
  select 160, b.id,
    format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %s, %s, %s) on conflict (id) do nothing;',
      b.id, b.name, case when b.public then 'true' else 'false' end, coalesce(b.file_size_limit::text, 'null'),
      coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'null'))
  from storage.buckets b
)
select ord, name, ddl from out order by ord, name;
